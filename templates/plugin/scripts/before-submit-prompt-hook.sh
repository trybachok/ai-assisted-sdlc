#!/usr/bin/env bash
# =============================================================================
# before-submit-prompt-hook.sh — заготовка хука события beforeSubmitPrompt.
#
# Срабатывает, когда пользователь нажал «отправить», но запрос ещё не ушёл.
# Позволяет проверить промпт (например, на секреты) и не пропустить его.
#
# ВХОД (stdin): JSON с общими полями и полями события:
#   prompt       текст промпта пользователя
#   attachments  вложения: массив объектов с полями type ("file" | "rule")
#                и file_path
#
# ВЫХОД (stdout): JSON с решением:
#   continue      boolean, основное поле ответа. true — отправить промпт,
#                 false — заблокировать отправку. Указывайте всегда.
#   user_message  [необязательный] текст для пользователя при блокировке.
#
# КОД ВЫХОДА: 0 — использовать JSON из stdout; 2 — заблокировать отправку;
#   любой другой — хук считается упавшим, и промпт отправляется, если для хука
#   не задан failClosed: true.
#
# Переменные окружения, доступные хуку, перечислены в observe-hook.sh.
# =============================================================================
set -euo pipefail

# Прочитать входной JSON целиком. Чтобы разобрать его, сохраните в переменную:
#   input="$(cat)"
#   prompt="$(printf '%s' "$input" | jq -r '.prompt // empty')"
cat > /dev/null

# Заготовка ничего не проверяет и всегда пропускает промпт.
# Замените на свою логику. Пример блокировки:
#   printf '%s\n' '{"continue": false, "user_message": "В промпте найден секрет"}'
printf '%s\n' '{"continue": true}'
