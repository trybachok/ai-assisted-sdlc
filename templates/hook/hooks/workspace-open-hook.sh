#!/usr/bin/env bash
# =============================================================================
# workspace-open-hook.sh — заготовка хука события workspaceOpen (App lifecycle
# hooks).
#
# Срабатывает, когда Cursor открывает проект, и при каждом изменении набора
# его папок. Чат для этого не нужен. Хук может вернуть папки с плагинами,
# которые Cursor загрузит для открытого проекта.
#
# ВХОД (stdin): JSON с полями hook_event_name, cursor_version, workspace_roots
#   (папки открытого проекта) и user_email. Полей чата (conversation_id,
#   generation_id, model, transcript_path) нет.
#
# ВЫХОД (stdout): один JSON-объект и больше ничего:
#   pluginPaths  [необязательный] массив абсолютных путей к папкам плагинов.
#                Пустой массив — дополнительных плагинов нет.
#
# КОД ВЫХОДА: 0 — использовать JSON из stdout; любой другой — хук считается
#   упавшим, проект открывается без его данных.
#
# Работает в приложении Cursor и в Cursor CLI. В облачных агентах не
# выполняется.
# Переменные окружения, доступные хуку, перечислены в observe-hook.sh.
# =============================================================================
set -euo pipefail

# Прочитать входной JSON целиком, даже если он не нужен.
cat > /dev/null

# Заготовка не добавляет плагинов.
# Замените на свои папки. Пример: плагин из папки tools/my-plugin проекта.
# Программа jq собирает правильный JSON, даже если в пути есть пробелы
# или кавычки; проверьте, что она установлена.
#   jq -n --arg path "$CURSOR_PROJECT_DIR/tools/my-plugin" '{pluginPaths: [$path]}'
printf '%s\n' '{"pluginPaths": []}'
