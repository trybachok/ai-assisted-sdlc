#!/usr/bin/env bash
# =============================================================================
# session-start-hook.sh — заготовка хука события sessionStart.
#
# Срабатывает, когда создан новый чат. Хук может добавить в него сведения
# (например, о проекте или команде) и задать переменные окружения для
# следующих хуков этого чата. Cursor не ждёт ответа хука и не может отменить
# создание чата.
#
# ВХОД (stdin): JSON с общими полями и полями события:
#   session_id           идентификатор чата
#   is_background_agent  true, если агент работает в фоне
#   composer_mode        режим чата: "agent", "ask" или "edit"
#
# ВЫХОД (stdout): один JSON-объект и больше ничего. Все поля необязательные:
#   additional_context  текст, который добавится в начальный контекст чата
#   env                 переменные окружения для следующих хуков этого чата:
#                       объект, в котором ключи и значения — строки
#
# КОД ВЫХОДА: 0 — использовать JSON из stdout; любой другой — хук считается
#   упавшим, чат создаётся без его данных.
#
# В облачных агентах sessionStart не выполняется.
# Переменные окружения, доступные хуку, перечислены в observe-hook.sh.
# =============================================================================
set -euo pipefail

# Прочитать входной JSON целиком. Чтобы разобрать его, сохраните в переменную.
# Для разбора нужна программа jq: проверьте, что она установлена.
#   input="$(cat)"
#   composer_mode="$(printf '%s' "$input" | jq -r '.composer_mode // empty')"
cat > /dev/null

# Заготовка ничего не добавляет.
# Замените на свои данные. Пример текста для агента:
#   printf '%s\n' '{"additional_context": "Отвечай на русском языке."}'
# Пример переменной окружения для следующих хуков:
#   printf '%s\n' '{"env": {"TEAM_NAME": "backend"}}'
printf '%s\n' '{}'
