#!/usr/bin/env bash
# =============================================================================
# before-submit-prompt-hook.sh — заготовка хука события beforeSubmitPrompt.
#
# Срабатывает, когда пользователь нажал «отправить», но запрос ещё не ушёл.
# Позволяет проверить запрос (например, на пароли и ключи) и не отправить его.
#
# ВХОД (stdin): JSON с общими полями и полями события:
#   prompt       текст запроса пользователя
#   attachments  вложения: массив объектов с полями type ("file" | "rule")
#                и file_path
#
# ВЫХОД (stdout): один JSON-объект с решением и больше ничего:
#   continue      указывайте всегда. true — отправить запрос, false — не
#                 отправлять.
#   user_message  [необязательный] текст для пользователя, если запрос
#                 не отправлен.
#
# КОД ВЫХОДА: 0 — использовать JSON из stdout; 2 — не отправлять запрос;
#   любой другой — хук считается упавшим, и запрос отправляется, если для хука
#   не задано "failClosed": true.
#
# Переменные окружения, доступные хуку, перечислены в observe-hook.sh.
# =============================================================================
set -euo pipefail

# Прочитать входной JSON целиком. Чтобы разобрать его, сохраните в переменную.
# Для разбора нужна программа jq: проверьте, что она установлена.
#   input="$(cat)"
#   prompt="$(printf '%s' "$input" | jq -r '.prompt // empty')"
cat > /dev/null

# Заготовка ничего не проверяет и всегда отправляет запрос.
# Замените на свою проверку. Пример отказа:
#   printf '%s\n' '{"continue": false, "user_message": "В запросе найден ключ доступа"}'
printf '%s\n' '{"continue": true}'
