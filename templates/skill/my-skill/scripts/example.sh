#!/usr/bin/env bash
# =============================================================================
# scripts/example.sh — пример скрипта навыка. Замените своим или удалите.
#
# Папка scripts/ НЕОБЯЗАТЕЛЬНА. В ней лежит исполняемый код, который агент
# запускает по указанию из SKILL.md. Язык любой: Bash, Python, JavaScript и т. д.
# Документация: https://cursor.com/docs/skills#including-scripts-in-skills
#
# Как подключить: сослаться на скрипт в SKILL.md относительным путём от папки
# навыка, например: «Запустить `scripts/example.sh <путь>`».
#
# Требования документации к скриптам:
#   - самодостаточность: скрипт не зависит от других файлов и от состояния чата;
#   - понятные сообщения об ошибках: агент читает их и решает, что делать дальше;
#   - аккуратная обработка граничных случаев (нет аргумента, нет файла и т. п.).
#
# Не забудьте сделать скрипт исполняемым: chmod +x scripts/example.sh
#
# Что делает этот пример: считает строки в файле или файлы в папке.
#   Использование: scripts/example.sh <путь-к-файлу-или-папке>
#   Код выхода:    0 — успех; 1 — путь не найден; 2 — неверные аргументы.
# =============================================================================
set -euo pipefail

usage() {
  echo "Использование: scripts/example.sh <путь-к-файлу-или-папке>" >&2
}

if [[ $# -ne 1 ]]; then
  echo "Ошибка: ожидается ровно один аргумент, получено: $#." >&2
  usage
  exit 2
fi

target="$1"

if [[ ! -e "$target" ]]; then
  echo "Ошибка: путь не найден: $target" >&2
  exit 1
fi

if [[ -d "$target" ]]; then
  count="$(find "$target" -type f | wc -l | tr -d ' ')"
  echo "Файлов в папке $target: $count"
else
  count="$(wc -l < "$target" | tr -d ' ')"
  echo "Строк в файле $target: $count"
fi
